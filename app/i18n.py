def get_lang(request_lang: Optional[str]) -> str:
    """Вернуть валидный код языка или английский по умолчанию."""
    if request_lang and request_lang in TRANSLATIONS:
        return request_lang
    return DEFAULT_LANG


def t(key: str, lang: str = DEFAULT_LANG) -> str:
    """
    Получить перевод. Если строки нет — вернуть английский вариант,
    если и его нет — вернуть сам ключ.
    """
    lang = get_lang(lang)
    value = TRANSLATIONS.get(lang, {}).get(key)
    if value is None:
        value = TRANSLATIONS[DEFAULT_LANG].get(key)
    return value if value is not None else key